"""Bridge vkuss_vill_v4 (П-4) payloads and publish the measured mounts; Gazebo runs separately.

Sensors: Livox Avia (cloud adapter + IMU frame), H-Flow (image flow, ToF range, IMU; via sensors.launch.py),
MindVision MV-SUA133GC (image + CameraInfo, optional: it renders 1280x1024 at 20 Hz while bridged).
All configs are generated by scripts/generate_vkuss_vill_v4.py.
"""
from pathlib import Path
import math
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription, OpaqueFunction
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue

NAME = 'vkuss_vill_v4'


def camera_bridges(context):
    if LaunchConfiguration('camera').perform(context).strip().lower() not in ('1', 'true', 'yes', 'on'):
        return []
    sim_time = ParameterValue(LaunchConfiguration('use_sim_time'), value_type=bool)
    base = '/'+NAME+'/mv133'
    # Same ROS name as the gz topic, so FAST-LIVO2 (img_topic) and fast_livo_sitl's own bridge agree;
    # full_system_sitl passes enable_camera:=false to fast_livo_sitl to avoid a second publisher.
    return [
        Node(package='ros_gz_bridge', executable='parameter_bridge', name=NAME+'_mv133_image_bridge',
             arguments=[base+'/image@sensor_msgs/msg/Image[gz.msgs.Image'],
             parameters=[{'use_sim_time': sim_time}], output='screen'),
        Node(package='ros_gz_bridge', executable='parameter_bridge', name=NAME+'_mv133_camera_info_bridge',
             arguments=[base+'/camera_info@sensor_msgs/msg/CameraInfo[gz.msgs.CameraInfo'],
             remappings=[(base+'/camera_info', base+'/camera_info_gz')],
             parameters=[{'use_sim_time': sim_time}], output='screen'),
        # gz CameraInfo carries the SDF cx/cy (OpenCV + 0.5 px); this node republishes OpenCV values.
        Node(package='gazebo_camera_tools', executable='camera_info', name=NAME+'_mv133_camera_info',
             parameters=[{'input_topic': base+'/camera_info_gz', 'output_topic': base+'/camera_info',
                          'use_sim_time': sim_time}], output='screen'),
    ]


def generate_launch_description():
    share = Path(get_package_share_directory('porter_sensor_adapters'))
    sim_time = ParameterValue(LaunchConfiguration('use_sim_time'), value_type=bool)
    return LaunchDescription([
        DeclareLaunchArgument('use_sim_time', default_value='true'),
        DeclareLaunchArgument('bridge_file', default_value=str(share/f'config/{NAME}_bridge.yaml')),
        DeclareLaunchArgument('camera', default_value='true',
                              description='Bridge the MindVision MV-SUA133GC image and CameraInfo (needed by FAST-LIVO2).'),
        DeclareLaunchArgument('avia_texel_fix', default_value='true'),
        # parameter_bridge (H-Flow, Avia, ground truth), H-Flow camera_info, hflow_adapter, range_adapters, sensor_frames.
        IncludeLaunchDescription(PythonLaunchDescriptionSource(str(share/'launch/sensors.launch.py')),
            launch_arguments={'config_file': str(share/f'config/{NAME}_sensors.json'),
                              'bridge_file': LaunchConfiguration('bridge_file'),
                              'use_sim_time': LaunchConfiguration('use_sim_time')}.items()),
        Node(package='livox_avia_cloud_adapter', executable='cloud_adapter', name=NAME+'_avia_cloud_adapter',
             parameters=[{'use_sim_time': sim_time, 'input_topic': f'/{NAME}/avia/raw_points',
                          'output_topic': f'/{NAME}/avia/points', 'frame_id': NAME+'_avia',
                          'scan_mode': 'nonrepetitive', 'pattern_edge_tolerance_rad': math.radians(.12),
                          'texel_fix': ParameterValue(LaunchConfiguration('avia_texel_fix'), value_type=bool)}], output='screen'),
        Node(package='porter_sensor_adapters', executable='avia_imu_frame', name=NAME+'_avia_imu_frame',
             parameters=[{'use_sim_time': sim_time, 'input_topic': f'/{NAME}/avia/raw_imu',
                          'output_topic': f'/{NAME}/avia/imu', 'frame_id': NAME+'_avia_imu'}], output='screen'),
        OpaqueFunction(function=camera_bridges),
    ])
